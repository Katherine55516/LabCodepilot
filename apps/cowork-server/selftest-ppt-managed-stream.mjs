import assert from 'node:assert/strict';
import {routineTextProgress} from './lib/routine-runner.mjs';
let clock=1000;const seen=[],p=routineTextProgress(event=>seen.push(event),()=>clock);
const delta=text=>({type:'stream_event',event:{type:'content_block_delta',delta:{type:'text_delta',text}}});
p.accept({type:'assistant',message:{content:[{type:'text',text:'Final only'}]}});
p.accept({type:'stream_event',event:{type:'content_block_delta',delta:{type:'input_json_delta',partial_json:'tool'}}});
assert.equal(seen.length,0,'non-text and final messages never become simulated typing');
p.accept(delta('{"title":"机制"'));assert.equal(seen.length,1);
clock+=100;p.accept(delta(',"body":"证据"}'));assert.equal(seen.length,1,'throttle');
p.flush();assert.equal(seen.length,2,'flush the actual final fragment even below the throttle');
assert.equal(seen[1].text,'{"title":"机制","body":"证据"}');assert.equal(seen[1].seq,2);
p.flush();assert.equal(seen.length,2,'unchanged final progress is not duplicated');
clock+=800;p.accept(delta('x'.repeat(70000)));assert.equal(seen[2].text.length,60000);assert.ok(seen[2].chars>70000);
const silent=routineTextProgress();silent.accept(delta('no consumer'));silent.flush();
console.log('PASS managed PPT text progress: actual deltas, monotonic sequence, throttle, final flush, bounded payload, no simulated final text');
const {pptModelInput}=await import('./lib/ppt-model-input.mjs');
const textInput=pptModelInput('source \n含中文');
assert.deepEqual(textInput.args,[]);assert.equal(textInput.frame.subarray(4,-4).toString(),'source \n含中文');assert.equal(textInput.frame.readUInt32BE(0),textInput.frame.length-8);
const visualInput=pptModelInput('Read source figure',[{id:'image_one',dataUrl:'data:image/png;base64,aGVsbG8='}]);
assert.deepEqual(visualInput.args,['--input-format','stream-json']);
const payload=JSON.parse(visualInput.frame.subarray(4,-4).toString());assert.equal(payload.message.content[0].text,'Read source figure');assert.deepEqual(payload.message.content[1],{type:'image',source:{type:'base64',media_type:'image/png',data:'aGVsbG8='}});
assert.equal(visualInput.frame.readUInt32BE(0),visualInput.frame.length-8);
assert.throws(()=>pptModelInput('x',[{dataUrl:'https://example.com/image.png'}]),/Invalid/);
console.log('PASS managed multimodal framing: actual stream-json user message, bounded embedded image, length framing; protocol fixture only');
