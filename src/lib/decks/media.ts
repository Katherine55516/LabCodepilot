import { lookup } from 'node:dns/promises';
import { isIP } from 'node:net';
import { isPrivateAddress } from '../ppt-gamma-image-fetch';
import { insertMedia } from './store';
import type { MediaItem } from './types';

/**
 * Media intake for Decks (report 04 §3). Input image URLs are fetched and
 * re-hosted locally, like Gamma's CDN re-hosting; a URL that cannot be fetched
 * is skipped (Gamma skips silently; we also report the count as a warning).
 *
 * Safety: only public HTTPS hosts (every resolved address must be public),
 * no redirects, a byte cap, and raster formats only. SVG is refused from
 * URLs and uploads because an SVG served from the app's own origin could run
 * script; the theme art is generated by our own code and never stored.
 */

export const MAX_MEDIA_BYTES = 10 * 1024 * 1024;
export const ALLOWED_IMAGE_MIME = ['image/png', 'image/jpeg', 'image/webp', 'image/gif', 'image/avif'] as const;

export function sniffImage(bytes: Uint8Array): (typeof ALLOWED_IMAGE_MIME)[number] | null {
  const b = Buffer.from(bytes.subarray(0, 16));
  if (b.length >= 8 && b.subarray(0, 8).equals(Buffer.from('89504e470d0a1a0a', 'hex'))) return 'image/png';
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return 'image/jpeg';
  if (b.length >= 6 && /^GIF8[79]a/.test(b.subarray(0, 6).toString('latin1'))) return 'image/gif';
  if (b.length >= 12 && b.subarray(0, 4).toString('latin1') === 'RIFF' && b.subarray(8, 12).toString('latin1') === 'WEBP') return 'image/webp';
  if (b.length >= 12 && b.subarray(4, 12).toString('latin1').startsWith('ftypavi')) return 'image/avif';
  return null;
}

/** PNG/JPEG/GIF/WebP pixel size from the header, when cheap to read. */
export function imageSize(bytes: Buffer, mime: string): { width: number; height: number } | undefined {
  try {
    if (mime === 'image/png') return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
    if (mime === 'image/gif') return { width: bytes.readUInt16LE(6), height: bytes.readUInt16LE(8) };
    if (mime === 'image/jpeg') {
      let i = 2;
      while (i < bytes.length) {
        if (bytes[i] !== 0xff) return undefined;
        const marker = bytes[i + 1];
        const len = bytes.readUInt16BE(i + 2);
        if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) return { height: bytes.readUInt16BE(i + 5), width: bytes.readUInt16BE(i + 7) };
        i += 2 + len;
      }
    }
  } catch { /* unknown size */ }
  return undefined;
}

export type FetchResult = { ok: true; data: Buffer; mime: string } | { ok: false; reason: string };

export async function fetchPublicImage(href: string, timeoutMs = 15_000): Promise<FetchResult> {
  let url: URL;
  try { url = new URL(href); } catch { return { ok: false, reason: 'invalid URL' }; }
  if (url.protocol !== 'https:') return { ok: false, reason: 'not HTTPS' };
  const host = url.hostname.replace(/^\[|\]$/g, '');
  try {
    const addresses = isIP(host) ? [{ address: host }] : await lookup(host, { all: true, verbatim: true });
    if (!addresses.length || addresses.some(a => isPrivateAddress(a.address))) return { ok: false, reason: 'host is not public' };
  } catch { return { ok: false, reason: 'host did not resolve' }; }
  try {
    const response = await fetch(url, { redirect: 'error', signal: AbortSignal.timeout(timeoutMs), headers: { accept: 'image/*' } });
    if (!response.ok || !response.body) return { ok: false, reason: `HTTP ${response.status}` };
    const declared = Number(response.headers.get('content-length'));
    if (Number.isFinite(declared) && declared > MAX_MEDIA_BYTES) return { ok: false, reason: 'larger than 10 MB' };
    const reader = response.body.getReader();
    const parts: Uint8Array[] = []; let total = 0;
    for (;;) {
      const { value, done } = await reader.read();
      if (done) break;
      total += value.byteLength;
      if (total > MAX_MEDIA_BYTES) { await reader.cancel(); return { ok: false, reason: 'larger than 10 MB' }; }
      parts.push(value);
    }
    const data = Buffer.concat(parts);
    const mime = sniffImage(data);
    return mime ? { ok: true, data, mime } : { ok: false, reason: 'not a PNG, JPEG, GIF, WebP or AVIF image' };
  } catch (error) {
    return { ok: false, reason: error instanceof Error && error.name === 'TimeoutError' ? 'timed out' : 'fetch failed' };
  }
}

/** Store validated bytes (uploads or fetched URLs). Throws for unsupported files. */
export function storeImage(deckId: string, data: Buffer, origin: MediaItem['origin'], meta: { sourceUrl?: string; prompt?: string } = {}): MediaItem {
  if (data.length > MAX_MEDIA_BYTES) throw new Error('Images must be 10 MB or smaller.');
  const mime = sniffImage(data);
  if (!mime) throw new Error('Use a PNG, JPEG, GIF, WebP or AVIF image.');
  return insertMedia(deckId, data, mime, origin, { ...imageSize(data, mime), ...meta });
}

/** Fetch every input URL (parallel, bounded); returns hosted media and the skipped URLs. */
export async function rehostInputImages(deckId: string, urls: string[], fetcher: typeof fetchPublicImage = fetchPublicImage) {
  const results = await Promise.all(urls.map(url => fetcher(url).then(r => ({ url, r }))));
  const media: MediaItem[] = [];
  const skipped: string[] = [];
  for (const { url, r } of results) {
    if (r.ok) media.push(storeImage(deckId, r.data, 'url', { sourceUrl: url }));
    else skipped.push(`${url} (${r.reason})`);
  }
  return { media, skipped };
}
